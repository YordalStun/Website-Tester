def _match(headers, signs):
    for name, contains, label in signs:
        value = headers.get(name)
        if value is not None and (contains is None or contains in value.lower()):
            if label:
                return label
    return ""


def cache_status(resp):
    """('HIT'/'MISS'/'BYPASS'/'' , header used)."""
    for name in CACHE_HEADERS:
        value = resp.header(name)
        if not value:
            continue
        low = value.lower()
        if any(w in low for w in ("hit", "cached", "static", "true")) or (name == "x-endurance-cache-level" and low.strip() not in ("0", "")):
            return "HIT", f"{name}: {value}"
        if any(w in low for w in ("miss", "expired", "stale", "updating", "revalidated")):
            return "MISS", f"{name}: {value}"
        return value.upper()[:20], f"{name}: {value}"
    age = resp.header("age")
    if age and age.strip().isdigit() and int(age) > 0:
        return "HIT", f"age: {age}"
    return "", ""


def _median(values):
    values = [v for v in values if v is not None]
    return statistics.median(values) if values else None


def sample(url, count, pause=0.4, cancelled=None, **kw):
    """Fetch the same address several times. Returns the list of responses."""
    out = []
    for i in range(count):
        if cancelled and cancelled():
            break
        out.append(net.fetch(url, **kw))
        if i < count - 1:
            time.sleep(pause)
    return out


def summarise(responses):
    good = [r for r in responses if not r.error and r.status]
    if not good:
        return None
    return {
        "count": len(good),
        "status": good[-1].status,
        "rtt": _median([r.timing.connect for r in good]),
        "tls": _median([r.timing.tls for r in good]),
        "wait": _median([r.timing.wait for r in good]),
        "think": _median([r.timing.think for r in good]),
        "think_min": min(r.timing.think for r in good),
        "think_max": max(r.timing.think for r in good),
        "total": _median([r.timing.total for r in good]),
        "download": _median([r.timing.download for r in good]),
        "cache": [cache_status(r)[0] for r in good],
    }


def lookup_location(ip=None):
    """Rough location / network owner of an IP (or of this PC when ip is None). Returns {} on failure."""
    url = f"https://ipinfo.io/{ip}/json" if ip else "https://ipinfo.io/json"
    try:
        info = net.get_json(url, timeout=8)
    except Exception:
        return {}
    if info.get("bogon"):
        return {}
    return info


def distance_km(loc_a, loc_b):
    try:
        lat1, lon1 = (float(x) for x in loc_a.split(","))
        lat2, lon2 = (float(x) for x in loc_b.split(","))
    except (AttributeError, ValueError):
        return None
    p1, p2 = math.radians(lat1), math.radians(lat2)
    dphi, dl = math.radians(lat2 - lat1), math.radians(lon2 - lon1)
    a = math.sin(dphi / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dl / 2) ** 2
    return 6371 * 2 * math.asin(math.sqrt(a))


def reverse_dns(ip):
    try:
        answer = dns.resolver.resolve(dns.reversename.from_address(ip), "PTR", lifetime=4)
        return answer[0].target.to_text().rstrip(".")
    except (dns.exception.DNSException, OSError, ValueError):
        return ""


def place(info):
    if not info:
        return ""
    bits = [info.get("city"), info.get("region"), info.get("country")]
    out = []
    for b in bits:
        if b and b not in out:
            out.append(b)
    return ", ".join(out)


def check_redirects(start_url, chain):
    """Findings about the redirect chain from what the visitor types to the real page."""
    findings = []
    data = {"chain": [(r.url, r.status, r.timing.total) for r in chain]}
    hops = [r for r in chain if r.is_redirect]
    cost = sum(r.timing.total for r in hops)
    data["redirect_ms"] = cost
    if len(hops) >= 2:
        findings.append(Finding(
            "server", WARNING, f"{len(hops)} redirects before the page loads ({cost:.0f} ms wasted)",
            "Each redirect is a whole extra round trip (often a new connection and SSL handshake too).",
            "Link to the final address everywhere, and redirect straight to it in one step - e.g. "
            "http://example.com -> https://www.example.com directly, not via https://example.com first.",
            impact=int(cost), items=[f"{r.status} {r.url} -> {r.header('location')}" for r in hops]))
    elif len(hops) == 1:
        h = hops[0]
        a, b = urlsplit(h.url), urlsplit(chain[-1].url)
        if cost > 500:
            findings.append(Finding(
                "server", WARNING, f"A slow redirect ({cost:.0f} ms) before the page loads",
                f"{h.url} redirects to {chain[-1].url}, and that redirect alone took {cost:.0f} ms. Redirects should "
                "take a few milliseconds - this one is probably handled by WordPress (or a plugin) instead of the "
                "web server.",
                "Do the redirect in the web server or CDN instead (cPanel > Domains/Redirects, .htaccess, or a "
                "Cloudflare Redirect Rule), and link to the final address everywhere.", impact=int(cost)))
        elif a.hostname != b.hostname and a.path in ("", "/"):
            findings.append(Finding(
                "server", INFO, f"Visitors to {a.hostname} are redirected to {b.hostname} ({cost:.0f} ms)",
                "That's normal, but make sure links, Google and adverts use the final address so visitors skip "
                "the redirect."))
    return findings, data


def check_http_redirect(host):
    """Does http:// send visitors to https://?"""
    chain = net.follow(f"http://{host}/", timeout=15)
    first = chain[0]
    last = chain[-1]
    if first.error:
        return None, []
    if last.url.startswith("https://"):
        return True, []
    return False, [Finding(
        "ssl", WARNING, "The site still works on insecure http:// without redirecting",
        "Visitors (and Google) can end up on the insecure version, and browsers mark it \"Not secure\".",
        "Redirect all http:// traffic to https:// (in your host's control panel, Cloudflare \"Always use HTTPS\", or "
        "the Really Simple SSL plugin).")]


def check_ssl(page, host):
    findings = []
    data = {}
    if not page.url.startswith("https://"):
        findings.append(Finding("ssl", CRITICAL, "The site doesn't use HTTPS",
                                "Browsers show \"Not secure\", Google ranks it lower, and HTTP/2 (faster) needs HTTPS.",
                                "Install a free Let's Encrypt certificate (most hosts: one click in cPanel > SSL/TLS "
                                "Status or AutoSSL) and redirect http to https."))
        return data, findings
    data["tls_version"] = page.tls_version
    data["cipher"] = page.cipher
    if page.cert_error:
        findings.append(Finding("ssl", CRITICAL, "The SSL certificate is not valid",
                                f"Browsers will show a big security warning: {page.cert_error}.",
                                "Reissue the certificate for this exact domain (including www if used) in your "
                                "hosting control panel.", impact=100000))
    cert = net.cert_summary(page.cert)
    data["cert"] = cert
    days = cert.get("days_left")
    if days is not None:
        if days < 0:
            findings.append(Finding("ssl", CRITICAL, "The SSL certificate has expired",
                                    "Visitors see a security warning instead of the site.",
                                    "Renew the certificate now (cPanel > SSL/TLS Status > Run AutoSSL)."))
        elif days < 14:
            findings.append(Finding("ssl", CRITICAL, f"The SSL certificate expires in {days} days",
                                    f"Issued by {cert.get('issuer')}. If it doesn't renew automatically visitors will see "
                                    "a security warning.", "Check auto-renewal is working, or renew it manually."))
        elif days < 30 and "let's encrypt" not in cert.get("issuer", "").lower():
            findings.append(Finding("ssl", WARNING, f"The SSL certificate expires in {days} days",
                                    f"Issued by {cert.get('issuer')}.", "Renew it soon."))
        else:
            findings.append(Finding("ssl", GOOD, f"SSL certificate is valid ({days} days left, {cert.get('issuer')})"))
    if page.tls_version in ("TLSv1", "TLSv1.1", "SSLv3"):
        findings.append(Finding("ssl", CRITICAL, f"Old, insecure encryption ({page.tls_version})",
                                "Modern browsers refuse or warn about this.", "Ask your host to enable TLS 1.2 and 1.3."))
    elif page.tls_version == "TLSv1.2":
        findings.append(Finding("ssl", INFO, "TLS 1.3 isn't used",
                                "TLS 1.3 sets up secure connections with one round trip less than TLS 1.2, so every "
                                "new visitor gets the page a little sooner.",
                                "Ask your host to enable TLS 1.3 (Cloudflare enables it automatically).",
                                impact=int(page.timing.connect)))
    elif page.tls_version == "TLSv1.3":
        findings.append(Finding("ssl", GOOD, "Uses TLS 1.3 (fastest secure connections)"))
    if page.timing.tls > 4 * max(page.timing.connect, 10) and page.timing.tls > 300:
        findings.append(Finding("ssl", WARNING, f"Slow SSL handshake ({page.timing.tls:.0f} ms)",
                                "Setting up the secure connection took far longer than the network distance explains, "
                                "which usually means a busy server or a long certificate chain.",
                                "Ask your host to check the server load and enable OCSP stapling and TLS session "
                                "resumption.", impact=int(page.timing.tls - 2 * page.timing.connect)))
    return data, findings


def check_server(page, chain, is_wp, static_url=None, progress=None, cancelled=None, samples=5, locate=True):
    """Timing samples and the 'is it the server or WordPress?' split. Returns (data, findings)."""
    findings = []
    data = {}
    url = page.url
    host = net.host_of(url)
    h = page.headers

    # --- Software, hosting, CDN
    data["server_header"] = h.get("server", "")
    data["powered_by"] = h.get("x-powered-by", "")
    data["cdn"] = _match(h, CDN_SIGNS)
    data["host_hint"] = _match(h, HOST_SIGNS)
    data["ip"] = page.ip

    # --- Timing samples
    def step(text):
        if progress:
            progress(text)
    step("Timing the home page (5 visits)")
    home = sample(url, samples, cancelled=cancelled)
    data["home"] = summarise(home)
    data["home_samples"] = [(r.timing.connect, r.timing.wait, r.timing.think, cache_status(r)[0]) for r in home if not r.error]
    step("Timing the page with the cache skipped")
    sep = "&" if "?" in url else "?"
    bust = sample(f"{url}{sep}nocache={random.randint(100000, 999999)}", 3, cancelled=cancelled)
    data["uncached"] = summarise(bust)
    if static_url:
        step("Timing a plain file (no WordPress involved)")
        data["static_url"] = static_url
        data["static"] = summarise(sample(static_url, 3, cancelled=cancelled, headers={"Accept": "*/*"}))
    if is_wp:
        step("Timing WordPress itself (admin-ajax.php)")
        ajax = sample(urljoin(url, "/wp-admin/admin-ajax.php"), 3, cancelled=cancelled, headers={"Accept": "*/*"})
        data["wp_backend"] = summarise(ajax)
        data["wp_backend_status"] = ajax[-1].status if ajax else None

    home_s = data["home"]
    if not home_s:
        findings.append(Finding("server", CRITICAL, "The server didn't answer our timing tests",
                                home[-1].error if home else "", impact=10000))
        return data, findings
    rtt = home_s["rtt"]
    think = home_s["think"]
    data["rtt"] = rtt

    # Distance / round trip
    me = lookup_location() if locate else {}
    there = lookup_location(page.ip) if locate and page.ip else {}
    data["tester_location"] = place(me)
    data["server_location"] = place(there)
    data["server_org"] = re.sub(r"^AS\d+\s+", "", there.get("org", ""))
    data["reverse_dns"] = reverse_dns(page.ip) if page.ip else ""
    km = distance_km(me.get("loc"), there.get("loc")) if me and there else None
    data["distance_km"] = km
    where = f" The server appears to be in {data['server_location']}" if data["server_location"] else ""
    if km is not None and data["tester_location"]:
        where += f", about {km:,.0f} km from you ({data['tester_location']})."
    elif where:
        where += "."
    if data["cdn"]:
        where += f" (It's behind {data['cdn']}, so this is the nearest {data['cdn']} location, not the real server.)"
    if rtt > 250:
        findings.append(Finding(
            "server", CRITICAL, f"The server is a long way away ({rtt:.0f} ms per round trip)",
            "Every connection needs several round trips before the page even starts to arrive." + where,
            "Host the site in the same country as most of your visitors, or put it behind a CDN such as Cloudflare "
            "(free) so visitors connect to a nearby location.", impact=int(rtt * 4)))
    elif rtt > 120:
        findings.append(Finding(
            "server", WARNING, f"The server is quite far away ({rtt:.0f} ms per round trip)",
            "Each new connection costs about 3-4 round trips." + where,
            "If most visitors are near you, consider hosting closer or using a CDN such as Cloudflare.",
            impact=int(rtt * 3)))
    else:
        findings.append(Finding("server", GOOD, f"Network distance is fine ({rtt:.0f} ms per round trip)",
                                where.strip()))

    # Server response time (the classic "TTFB")
    statuses = home_s["cache"]
    hit = any(s == "HIT" for s in statuses)
    if think > 1500:
        sev, label = CRITICAL, "very slow"
    elif think > 600:
        sev, label = CRITICAL, "slow"
    elif think > 250:
        sev, label = WARNING, "a bit slow"
    elif think < 15:
        sev, label = GOOD, "instant"
    else:
        sev, label = GOOD, "fast"
    text = (f"After the request arrives, the server takes about {think:.0f} ms to start sending the page "
            f"(fastest {home_s['think_min']:.0f} ms, slowest {home_s['think_max']:.0f} ms over {home_s['count']} visits).")
    findings.append(Finding("server", sev, f"Server response is {label}" + ("" if label == "instant" else f" ({think:.0f} ms)"),
                            text,
                            "" if sev == GOOD else "See the diagnosis at the top of the report for what's causing it.",
                            impact=int(max(0, think - 150)), symptom=True))
    if home_s["think_max"] > 3 * max(home_s["think_min"], 50) and home_s["think_max"] - home_s["think_min"] > 400:
        findings.append(Finding(
            "server", WARNING, "Response times jump around a lot",
            f"The same page took between {home_s['think_min']:.0f} and {home_s['think_max']:.0f} ms. Inconsistent "
            "times usually mean an overloaded shared server, a cache that keeps emptying, or something (backups, "
            "cron jobs, bots) hogging the server.",
            "Ask your host whether the server is overloaded; check for heavy scheduled tasks and block bad bots "
            "(Cloudflare / Wordfence rate limiting).", impact=int((home_s["think_max"] - home_s["think_min"]) / 3)))

    # --- Where does the server time go?
    static = data.get("static")
    backend = data.get("wp_backend")
    uncached = data.get("uncached")
    if static:
        data["static_think"] = static["think"]
        if static["think"] > 300:
            findings.append(Finding(
                "server", CRITICAL, f"Even simple files are slow ({static['think']:.0f} ms)",
                "A plain file that doesn't involve WordPress at all still took this long. That means the server "
                "itself is overloaded or underpowered - this is a hosting problem, not a WordPress problem.",
                "Upgrade to a better hosting plan or move host. Cheap shared hosting is the usual cause.",
                impact=int(static["think"] - 50)))
        elif static["think"] > 120:
            findings.append(Finding(
                "server", WARNING, f"Simple files are a bit slow ({static['think']:.0f} ms)",
                "A plain file took longer than a healthy server needs (usually under 50 ms). The server may be busy.",
                "Use a CDN (Cloudflare) to serve files from nearby, and ask your host about server load.",
                impact=int(static["think"] - 50)))
    if backend:
        data["wp_think"] = backend["think"]
        base = static["think"] if static else 0
        wp_cost = max(0.0, backend["think"] - base)
        if backend["think"] > 1000:
            findings.append(Finding(
                "wordpress", CRITICAL, f"WordPress itself is slow to start up ({backend['think']:.0f} ms)",
                "We timed admin-ajax.php, which loads WordPress and all active plugins but no page content. "
                f"About {wp_cost:.0f} ms of that is WordPress, plugins and the database. Everything that can't be "
                "cached (first visits, logged-in users, shop carts, forms, searches) pays this.",
                "1) Deactivate plugins one at a time and re-test to find the slow one (the Query Monitor plugin shows "
                "slow plugins and database queries - remove it afterwards). 2) Make sure PHP is a recent version. "
                "3) Clean up the database (WP-Optimize: old revisions, transients, autoloaded options). 4) Ask your "
                "host to enable an object cache (Redis/Memcached).", impact=int(wp_cost)))
        elif backend["think"] > 400:
            findings.append(Finding(
                "wordpress", WARNING, f"WordPress takes a while to start up ({backend['think']:.0f} ms)",
                "admin-ajax.php (WordPress + plugins, no page content) took this long. A lean WordPress site does "
                "this in under 300 ms.",
                "Remove plugins you don't need, update PHP, clean the database, and ask about an object cache.",
                impact=int(wp_cost / 2)))
        else:
            findings.append(Finding("wordpress", GOOD, f"WordPress starts up quickly ({backend['think']:.0f} ms)"))
    if uncached and think and uncached["think"] > think + 300 and hit:
        findings.append(Finding(
            "caching", INFO, "The page cache is hiding a slow server",
            f"Cached pages come back in {think:.0f} ms, but when the cache is skipped the page takes "
            f"{uncached['think']:.0f} ms. Most visitors get the fast version, but first visitors after the cache "
            "clears, logged-in users and visitors with shopping carts get the slow one.",
            "Keep the cache, and also speed up WordPress itself (see the WordPress and Plugins sections) so "
            "uncached pages aren't so slow. Use \"cache preload\" so the cache is rebuilt before visitors arrive."))
    data["uncached_think"] = uncached["think"] if uncached else None

    # --- Page caching
    page_cache = hit or any(sign in page.text[-3000:] for sign in HTML_CACHE_SIGNS)
    data["page_cache"] = page_cache
    data["cache_header"] = next((cache_status(r)[1] for r in home if cache_status(r)[1]), "")
    if page_cache:
        findings.append(Finding("caching", GOOD, "Page caching is working",
                                data["cache_header"] or "A caching plugin's signature was found in the page."))
    elif is_wp and think < 200:
        findings.append(Finding("caching", INFO, "No page cache detected, but pages come back fast",
                                f"We couldn't see a caching plugin or cache header, but the server answers in "
                                f"{think:.0f} ms, so pages are probably cached in a way that doesn't show."))
    elif is_wp:
        sev = CRITICAL if think > 400 else WARNING
        findings.append(Finding(
            "caching", sev, "No page caching found",
            "Without page caching, WordPress builds every page from scratch (running PHP, every plugin and many "
            f"database queries) for every visitor. Right now that takes about {think:.0f} ms each time.",
            "Install ONE caching plugin. Best choice depends on your server: LiteSpeed server -> LiteSpeed Cache; "
            "SiteGround -> SiteGround Speed Optimizer; otherwise WP Rocket (paid) or WP Super Cache / W3 Total Cache "
            "(free). Cached pages typically come back in under 100 ms.", impact=int(max(think - 80, 100))))
    if data["cdn"] == "Cloudflare" and "DYNAMIC" in (h.get("cf-cache-status", "").upper()):
        findings.append(Finding(
            "caching", INFO, "Cloudflare doesn't cache your pages (only files)",
            "cf-cache-status: DYNAMIC means every page request still goes all the way to your server.",
            "Cloudflare APO for WordPress ($5/month) or a Cache Rule for HTML pages lets Cloudflare serve whole "
            "pages from nearby, which removes most of the server wait for visitors."))
    if data["cdn"]:
        findings.append(Finding("caching", GOOD, f"Uses a CDN ({data['cdn']})"))
    elif rtt > 80:
        findings.append(Finding(
            "caching", WARNING, "No CDN",
            f"Every file comes all the way from the server ({rtt:.0f} ms each round trip from you).",
            "Put the site behind a CDN. Cloudflare's free plan is the easiest: change the nameservers and your "
            "images, CSS and JS are served from a location near each visitor.", impact=int(rtt * 2)))
    else:
        findings.append(Finding("caching", INFO, "No CDN detected",
                                "The server is close to you so it's fast here, but visitors in other countries would "
                                "benefit from a CDN such as Cloudflare."))

    # --- Protocols and compression
    if url.startswith("https://"):
        alpn = net.probe_alpn(host, urlsplit(url).port or 443)
        data["http2"] = alpn == "h2"
        alt = h.get("alt-svc", "")
        data["http3"] = "h3" in alt
        if alpn == "h2":
            findings.append(Finding("server", GOOD, "HTTP/2 is on" + (" (and HTTP/3)" if data["http3"] else "")))
        elif alpn is not None:
            findings.append(Finding(
                "server", WARNING, "HTTP/2 isn't switched on",
                "With the old HTTP/1.1, browsers can only download about 6 files at a time from your server. "
                "HTTP/2 downloads them all at once over one connection.",
                "Ask your host to enable HTTP/2 (most good hosts have it on), or use Cloudflare which adds it "
                "automatically.", impact=200))
    enc = page.header("content-encoding").lower()
    data["compression"] = enc or "none"
    if not enc and len(page.body) > 2048:
        findings.append(Finding(
            "caching", CRITICAL if len(page.body) > 50 * 1024 else WARNING, "The page is sent uncompressed",
            f"The HTML ({len(page.body) // 1024} KB) would shrink to roughly a quarter with GZIP/Brotli compression.",
            "Turn on GZIP or Brotli compression on the server (cPanel: Optimize Website; or your caching plugin; or "
            "Cloudflare does it automatically).", impact=int(len(page.body) / 1024 * 0.75)))
    elif enc == "br":
        findings.append(Finding("caching", GOOD, "Pages are compressed with Brotli"))
    elif enc:
        findings.append(Finding("caching", GOOD, f"Pages are compressed ({enc})",
                                "Brotli compression is a little smaller still, if your host/CDN supports it."))

    # --- PHP version
    php = re.search(r"PHP/(\d+)\.(\d+)(?:\.(\d+))?", data["powered_by"] + " " + data["server_header"])
    if php:
        major, minor = int(php.group(1)), int(php.group(2))
        version = php.group(0).split("/")[1]
        data["php"] = version
        eol = PHP_EOL.get((major, minor))
        today = date.today()
        if (major, minor) < (7, 4) or (eol and eol < today):
            findings.append(Finding(
                "server", CRITICAL, f"Old, unsupported PHP version ({version})",
                f"PHP {major}.{minor} no longer gets security fixes" + (f" (since {eol:%B %Y})" if eol else "") +
                ". Newer PHP versions are also much faster - PHP 8.x runs WordPress noticeably quicker than 7.x.",
                "Change the PHP version in your hosting control panel (cPanel: \"Select PHP Version\" or "
                "\"MultiPHP Manager\") to 8.3 or newer. Test the site afterwards; update plugins first.",
                impact=300))
        elif eol and (eol - today).days < 180:
            findings.append(Finding(
                "server", WARNING, f"PHP {version} stops getting security fixes soon ({eol:%B %Y})",
                "", "Plan to move to PHP 8.3 or newer in your hosting control panel."))
        else:
            findings.append(Finding("server", GOOD, f"PHP {version} is a supported version"))
        findings.append(Finding("security", INFO, "The server reveals its PHP version",
                                f"X-Powered-By: {data['powered_by']}", "Ask your host to hide it (expose_php = Off)."))
    return data, findings
